const CATALOG: Record<Language, Record<MessageKey, string>> = { en: EN, ru: RU }

let activeLanguage: Language = DEFAULT_LANGUAGE

/** The active language is intentionally module-level: the formatters below are
 *  pure helpers, and every screen re-renders when the preference changes. */
export function setActiveLanguage(language: Language): void {
  activeLanguage = language
}

export function getLanguage(): Language {
  return activeLanguage
}

export function localeOf(language: Language = activeLanguage): string {
  return language === 'ru' ? 'ru-RU' : 'en-GB'
}

export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string

export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const template = CATALOG[activeLanguage][key] ?? EN[key] ?? key
  if (!vars) return template
  let text = template
  for (const [name, value] of Object.entries(vars)) {
    text = text.split(`{${name}}`).join(String(value))
  }
  return text
}

/** Russian needs three forms; English only distinguishes one and many. */
export function pluralize(count: number, forms: { one: string; few: string; many: string }): string {
  if (activeLanguage === 'en') return count === 1 ? forms.one : forms.many
  const mod10 = count % 10
  const mod100 = count % 100
  if (mod10 === 1 && mod100 !== 11) return forms.one
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return forms.few
  return forms.many
}
